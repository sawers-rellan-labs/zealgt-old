#!/usr/bin/env bash
# bin/build_envs.sh — build every zealgt environment once, from the repo, into /share (never at task time, never on /rsstu).
#
# Environments (PLAN §2 rule 6; build prompt "Environments, the reproducible way"):
#   envs/<name>/environment.yml            non-module envs (the Nextflow launcher: envs/nextflow), built first
#   modules/nf-core/<tool>[/<sub>]/environment.yml   nf-core modules, the yml they ship with (never edited)
#   modules/local/<module>/environment.yml           local modules
#   + an optional build.sh next to the environment.yml for tools that are not conda packages (pinned commit, compiled
#     with the compilers pinned in that environment.yml, installed into $CONDA_PREFIX). build.sh runs inside the new env
#     (`conda run -p <prefix>`) with ZG_ENV_DIR (its own directory) and ZG_BUILD_DIR (a scratch dir inside the prefix,
#     kept as the source record) exported. Declare the pinned source(s) in build.sh with lines `# zg-source: <url>@<commit>`.
#
# Env id: path under envs/, modules/nf-core/ or modules/local/ with "/" -> "_" (samtools/stats -> samtools_stats);
# process name = upper-case id (SAMTOOLS_STATS). Aliased includes are mapped in envs/process_aliases.tsv (alias<TAB>env_id).
# Prefix: ${ZG_ENV_ROOT}/<id>-<sha8>, sha8 = first 8 hex of sha256( environment.yml bytes ++ build.sh bytes if present ).
# A prefix that already exists with its success record (.zg_env_info.tsv) is skipped; a prefix that exists WITHOUT it (a
# failed earlier build) is reported and left alone — this script never deletes anything; remove it by hand, with consent.
#
# Smoke test: the command in envs/smoke_tests.tsv (env_id<TAB>command, run inside the env) if listed; always also a check
# that every pinned dependency of environment.yml is installed at the pinned version/build (`conda list --export`).
#
# Usage
#   bin/build_envs.sh --list            id, process, env dir, sha8, prefix (no conda needed; works on the laptop)
#   bin/build_envs.sh --write-config    regenerate conf/env_prefixes.config (withName -> prefix); run locally, commit
#   bin/build_envs.sh [--only <id>]...  build (hazel, as the xfer job bin/build_envs.sbatch; compute nodes are offline)
#   bin/build_envs.sh --check-config    exit 1 if conf/env_prefixes.config is stale (also run before every build)
#
# Output: ${ZG_ENV_ROOT}/manifest.tsv and envs/manifest.tsv (module, process, prefix, sha8, status, sources, tool
# versions, file count, build time, conda version). envs/manifest.tsv is a build record of the hazel checkout (gitignored).

set -eo pipefail

ZG_ENV_ROOT="${ZG_ENV_ROOT:-/share/maize/frodrig4/conda/zealgt}"
ZG_CONDA="${ZG_CONDA:-/usr/local/apps/conda/miniconda3/26.3.2/bin/conda}"
export CONDA_PKGS_DIRS="${CONDA_PKGS_DIRS:-/share/maize/frodrig4/conda/pkgs}"
export CONDA_CHANNEL_PRIORITY=strict

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CONFIG_OUT="$REPO/conf/env_prefixes.config"

die() { echo "build_envs: ERROR: $*" >&2; exit 1; }
log() { echo "build_envs: $(date '+%F %T') $*" >&2; }

sha256_stdin() {
    if command -v sha256sum >/dev/null 2>&1; then sha256sum | cut -c1-64
    else shasum -a 256 | cut -c1-64; fi
}

# env_sha8 <env dir>
env_sha8() {
    local d="$1"
    if [ -f "$d/build.sh" ]; then cat "$d/environment.yml" "$d/build.sh"; else cat "$d/environment.yml"; fi | sha256_stdin | cut -c1-8
}

# Prints: id<TAB>process<TAB>env_dir(relative to repo)<TAB>sha8<TAB>prefix, launcher (envs/nextflow) first.
list_envs() {
    local f d rel id
    {
        for f in "$REPO"/envs/*/environment.yml; do
            [ -f "$f" ] || continue
            d="$(dirname "$f")"; rel="${d#"$REPO"/}"; id="${rel#envs/}"
            [ "$id" = "nextflow" ] && printf '0\t%s\t%s\n' "$id" "$rel" || printf '1\t%s\t%s\n' "$id" "$rel"
        done
        for base in modules/nf-core modules/local; do
            [ -d "$REPO/$base" ] || continue
            while IFS= read -r f; do
                d="$(dirname "$f")"; rel="${d#"$REPO"/}"; id="${rel#"$base"/}"; id="${id//\//_}"
                printf '2\t%s\t%s\n' "$id" "$rel"
            done < <(find "$REPO/$base" -name environment.yml -not -path '*/tests/*' | sort)
        done
    } | sort -t$'\t' -k1,1 -k2,2 | while IFS=$'\t' read -r _ id rel; do
        local sha; sha="$(env_sha8 "$REPO/$rel")"
        printf '%s\t%s\t%s\t%s\t%s\n' "$id" "$(echo "$id" | tr '[:lower:]-' '[:upper:]_')" "$rel" "$sha" "$ZG_ENV_ROOT/$id-$sha"
    done
}

check_unique() {
    local dup
    dup="$(list_envs | cut -f1 | sort | uniq -d)"
    [ -z "$dup" ] || die "env ids not unique (same module name under nf-core and local?): $dup"
}

render_config() {
    echo '// GENERATED by bin/build_envs.sh --write-config — do not edit by hand; rerun it after adding or changing a module env.'
    echo '// Points every process at its prebuilt prefix under /share (built by bin/build_envs.sbatch, an xfer job), so no env'
    echo '// is ever created at task time (compute nodes are offline). Prefix = <env id>-<sha8 of environment.yml + build.sh>.'
    echo '// Included by conf/hazel.config and conf/local.config only.'
    echo 'process {'
    local id proc rel sha prefix
    while IFS=$'\t' read -r id proc rel sha prefix; do
        [ "$id" = "nextflow" ] && continue
        printf "    withName: '%s' { conda = '%s' }\n" "$proc" "$prefix"
    done < <(list_envs)
    if [ -f "$REPO/envs/process_aliases.tsv" ]; then
        local alias target line
        while IFS=$'\t' read -r alias target; do
            case "$alias" in ''|'#'*) continue;; esac
            line="$(list_envs | awk -F'\t' -v t="$target" '$1==t {print $5}')"
            [ -n "$line" ] || die "envs/process_aliases.tsv: unknown env id '$target' for alias '$alias'"
            printf "    withName: '%s' { conda = '%s' }\n" "$alias" "$line"
        done < "$REPO/envs/process_aliases.tsv"
    fi
    echo '}'
}

check_config() {
    [ -f "$CONFIG_OUT" ] || die "conf/env_prefixes.config missing; run bin/build_envs.sh --write-config locally and commit it"
    if ! diff -q <(render_config) "$CONFIG_OUT" >/dev/null; then
        diff <(render_config) "$CONFIG_OUT" >&2 || true
        die "conf/env_prefixes.config is stale (an environment.yml / build.sh changed); rerun --write-config locally and commit"
    fi
}

# deps of an environment.yml as name<TAB>version<TAB>build (version/build empty when not pinned); pip sections skipped.
yml_deps() {
    awk '
        /^dependencies:/ { in_deps = 1; ind = -1; next }
        in_deps && /^[^ \t-]/ { in_deps = 0 }
        in_deps && /^[ ]*- / {
            match($0, /^[ ]*/); i = RLENGTH
            if (ind < 0) ind = i
            if (i != ind) next                       # nested list (pip:) items
            s = $0; sub(/^[ ]*- /, "", s); sub(/[ \t]*#.*$/, "", s); gsub(/[ \t"\047]/, "", s)
            if (s ~ /^pip:?$/ || s == "") next
            sub(/^.*::/, "", s)
            if (s ~ /[<>!~*]/) { split(s, b, /[<>!~=*]/); print b[1] "\t\t"; next }
            n = split(s, a, "=")
            if (n >= 3) print a[1] "\t" a[2] "\t" a[3]; else if (n == 2) print a[1] "\t" a[2] "\t"; else print a[1] "\t\t"
        }' "$1"
}

# verify_pins <prefix> <yml> ; prints the checked pins as name=version=build;... and fails on a mismatch
verify_pins() {
    local prefix="$1" yml="$2" exported name ver build hit out=""
    exported="$("$ZG_CONDA" list -p "$prefix" --export)"
    while IFS=$'\t' read -r name ver build; do
        # conda normalises names to lower case; the nf-core yml may pin e.g. "bioconda::multiqc=1.25.1"
        name="$(echo "$name" | tr '[:upper:]' '[:lower:]')"
        hit="$(echo "$exported" | awk -F= -v n="$name" '$1==n {print; exit}')"
        [ -n "$hit" ] || { echo "missing package $name in $prefix" >&2; return 1; }
        if [ -n "$ver" ] && [ "$(echo "$hit" | cut -d= -f2)" != "$ver" ]; then
            echo "version mismatch for $name: pinned $ver, installed $hit" >&2; return 1
        fi
        if [ -n "$build" ] && [ "$(echo "$hit" | cut -d= -f3)" != "$build" ]; then
            echo "build mismatch for $name: pinned $build, installed $hit" >&2; return 1
        fi
        out="${out:+$out;}$hit"
    done < <(yml_deps "$yml")
    echo "$out"
}

smoke_cmd() {
    [ -f "$REPO/envs/smoke_tests.tsv" ] || return 0
    awk -F'\t' -v id="$1" '$1==id { print substr($0, index($0, "\t") + 1); exit }' "$REPO/envs/smoke_tests.tsv"
}

# manifest row: module process prefix sha8 status sources tool_versions n_files built_at conda
row() { printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$@"; }

build_one() {
    local id="$1" proc="$2" rel="$3" sha="$4" prefix="$5"
    local dir="$REPO/$rel" info="$prefix/.zg_env_info.tsv" sources pins smoke smoke_out nfiles cv
    cv="$("$ZG_CONDA" --version 2>&1)"
    sources="$(grep -hoE '^# zg-source: .*' "$dir/build.sh" 2>/dev/null | sed 's/^# zg-source: //' | paste -sd, - || true)"
    fail() { log "FAILED $id: $1"; row "$id" "$proc" "$prefix" "$sha" "failed_$2" "$sources" "" "" "$(date '+%F %T')" "$cv"; return 1; }
    if [ -f "$info" ]; then
        log "skip $id: $prefix exists (built $(tail -1 "$info" | cut -f9))"
        tail -1 "$info" | awk -F'\t' 'BEGIN{OFS="\t"} {$5="skipped_exists"; print}'
        return 0
    fi
    if [ -e "$prefix" ]; then
        fail "$prefix exists without .zg_env_info.tsv (an earlier build failed); left untouched, remove it by hand" stale_prefix
        return 1
    fi
    log "build $id -> $prefix"
    "$ZG_CONDA" env create -p "$prefix" -f "$dir/environment.yml" >&2 || { fail "conda env create" create; return 1; }
    if [ -f "$dir/build.sh" ]; then
        local bdir="$prefix/share/zg_build"
        mkdir -p "$bdir"
        log "build.sh for $id (sources: ${sources:-none declared})"
        ZG_ENV_DIR="$dir" ZG_BUILD_DIR="$bdir" "$ZG_CONDA" run -p "$prefix" --no-capture-output bash "$dir/build.sh" >&2 \
            || { fail "build.sh" build_sh; return 1; }
    fi
    pins="$(verify_pins "$prefix" "$dir/environment.yml")" || { fail "pinned packages not as specified" pins; return 1; }
    smoke="$(smoke_cmd "$id")"
    smoke_out="pins_ok"
    if [ -n "$smoke" ]; then
        smoke_out="$("$ZG_CONDA" run -p "$prefix" bash -c "$smoke" 2>&1)" || { fail "smoke test '$smoke': $smoke_out" smoke; return 1; }
        smoke_out="$(echo "$smoke_out" | grep -v '^[[:space:]]*$' | head -1 | tr '\t' ' ' | sed 's/^[[:space:]]*//; s/[[:space:]]*$//')"
    fi
    nfiles="$(find "$prefix" | wc -l | tr -d ' ')"
    row "$id" "$proc" "$prefix" "$sha" "built" "$sources" "$smoke_out | $pins" "$nfiles" "$(date '+%F %T')" "$cv" | tee "$info"
    log "ok $id ($nfiles files): $smoke_out"
}

MANIFEST_HEADER=$'module\tprocess\tprefix\tsha8\tstatus\tsources\ttool_versions\tn_files\tbuilt_at\tconda'

main_build() {
    local only=("$@") rows rc=0 id proc rel sha prefix row
    [ -x "$ZG_CONDA" ] || die "conda binary not found at $ZG_CONDA"
    case "$ZG_ENV_ROOT" in /rsstu/*) die "ZG_ENV_ROOT on /rsstu is not allowed (too slow; user 2026-09-28)";; esac
    check_unique
    if [ "${ZG_ALLOW_STALE_CONFIG:-}" = 1 ]; then log "WARNING: config check skipped (ZG_ALLOW_STALE_CONFIG=1, testing only)"; else check_config; fi
    mkdir -p "$ZG_ENV_ROOT" "$CONDA_PKGS_DIRS"
    log "root $ZG_ENV_ROOT, pkgs $CONDA_PKGS_DIRS, $("$ZG_CONDA" --version 2>&1), channel priority $CONDA_CHANNEL_PRIORITY, host $(hostname)"
    rows="$MANIFEST_HEADER"
    while IFS=$'\t' read -r id proc rel sha prefix; do
        if [ "${#only[@]}" -gt 0 ] && ! printf '%s\n' "${only[@]}" | grep -qxF "$id"; then
            # not selected: keep it in the manifest as it stands on disk
            if [ -f "$prefix/.zg_env_info.tsv" ]; then
                row="$(tail -1 "$prefix/.zg_env_info.tsv" | awk -F'\t' 'BEGIN{OFS="\t"} {$5="present"; print}')"
            else
                row="$(row "$id" "$proc" "$prefix" "$sha" "not_built" "" "" "" "" "")"
            fi
            rows="$rows"$'\n'"$row"
            continue
        fi
        if row="$(build_one "$id" "$proc" "$rel" "$sha" "$prefix")"; then :; else rc=1; fi
        [ -n "$row" ] && rows="$rows"$'\n'"$row"
        # the launcher env comes first; stop if it failed (nothing downstream can run without it)
        if [ "$id" = "nextflow" ] && [ "$rc" -ne 0 ]; then log "launcher env failed; stopping"; break; fi
    done < <(list_envs)
    printf '%s\n' "$rows" > "$ZG_ENV_ROOT/manifest.tsv"
    cp "$ZG_ENV_ROOT/manifest.tsv" "$REPO/envs/manifest.tsv"
    log "manifest: $ZG_ENV_ROOT/manifest.tsv (copied to envs/manifest.tsv); exit $rc"
    return "$rc"
}

case "${1:-}" in
    --list)         check_unique; list_envs ;;
    --write-config) check_unique; render_config > "$CONFIG_OUT"; echo "wrote $CONFIG_OUT" >&2 ;;
    --check-config) check_unique; check_config; echo "conf/env_prefixes.config is current" >&2 ;;
    --deps)         yml_deps "$2" ;;
    --only)         shift; ids=(); while [ $# -gt 0 ]; do [ "$1" = "--only" ] || ids+=("$1"); shift; done; main_build "${ids[@]}" ;;
    "")             main_build ;;
    -h|--help)      awk 'NR > 1 && /^set -eo/ {exit} NR > 1 {print}' "${BASH_SOURCE[0]}" ;;
    *)              die "unknown argument '$1' (see --help)" ;;
esac
